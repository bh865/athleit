// The registration validation lives once, in packages/core (typed, unit-tested). Edge Functions are deployed
// from supabase/functions only, so a COPY is committed under _shared/registration/core. A unit test
// (packages/core/src/registration-edge-sync.test.ts) fails if the copy drifts; run this script to refresh it.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FILES = ['registration.ts', 'schemas/registration.ts'];
export function transform(src) {
  return (
    '// GENERATED by scripts/sync-edge-registration.mjs from packages/core/src. Do not edit here.\n' +
    src
      .replace(/from 'zod'/g, "from 'npm:zod@4.6.7'")
      .replace(/from '(\.{1,2}\/[^']+?)(?<!\.ts)'/g, "from '$1.ts'")
  );
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const f of FILES) {
    const out = join(root, 'supabase/functions/_shared/registration/core', f);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, transform(readFileSync(join(root, 'packages/core/src', f), 'utf8')));
    console.log('wrote', out);
  }
}
